--- One value as a stable string: a color table by its four channels, a number at full precision.
local function ser(v)
    local t = type(v)
    if t == "table" then
        return ("{%s,%s,%s,%s}"):format(ser(v.r), ser(v.g), ser(v.b), ser(v.a))
    elseif t == "number" then
        return ("%.17g"):format(v)
    elseif t == "string" then
        return ("%q"):format(v)
    end
    return tostring(v)
end

--- Every schema row as "path type default min max step", sorted by path.
local function snapshot(NS)
    local out = {}
    for _, def in ipairs(NS.Settings.Schema) do
        out[#out + 1] = table.concat({
            def.path, tostring(def.type), ser(def.default),
            ser(def.min), ser(def.max), ser(def.step),
        }, " ")
    end
    table.sort(out)
    return out
end

