-- The guard for item 020 (settings layout, KC-LY of the 2026-10-24 run): the layout pass moves,
-- regroups and relabels rows, and NOTHING ELSE. Every stored path, its type, its default and its
-- range are pinned here as they stood before the first layout edit, so a move that drops a row, a
-- relabel that slips a key, or a merge that touches a default fails this case instead of reaching
-- a player's profile. The page, tab, subsection, label and tooltip are deliberately NOT pinned:
-- those are what the pass is allowed to change.

